#!/usr/bin/env node
// Regenerates packages/agent/src/context/docs.gen.ts from
// resources/suna-context/*.md + resources/suna-skill/SKILL.md.
//
// The stock SunaContext docs ship as an embedded module (zero packaging
// changes — the Electron main bundle and the esbuild MCP bundle carry them
// automatically). The .md files are the SOURCE; the .gen.ts is checked in
// and drift-gated by packages/agent/src/context/context.test.ts.
//
//   node scripts/gen-suna-context.mjs
import * as fs from 'node:fs'
import * as path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = path.join(repoRoot, 'resources', 'suna-context')
const skillPath = path.join(repoRoot, 'resources', 'suna-skill', 'SKILL.md')
const outPath = path.join(repoRoot, 'packages', 'agent', 'src', 'context', 'docs.gen.ts')

/**
 * Line endings are normalised on the way in. These bytes are not a file on
 * disk: they are embedded into a generated module and handed to a model as
 * context, and the hash below is their identity. `.gitattributes` pins these
 * trees to LF as well; this is the half that does not depend on how the tree
 * was checked out.
 */
const lf = (text) => text.replace(/\r\n/g, '\n')

/** Pure so the drift-gate test can compare without touching the tree. */
export function generate() {
  const names = fs
    .readdirSync(srcDir)
    .filter((n) => n.endsWith('.md'))
    .sort()
  if (names.length === 0) throw new Error(`no .md files in ${srcDir}`)

  const files = {}
  const hasher = createHash('sha256')
  for (const n of names) {
    const body = lf(fs.readFileSync(path.join(srcDir, n), 'utf8'))
    files[n] = body
    hasher.update(n).update('\0').update(body).update('\0')
  }
  const skill = lf(fs.readFileSync(skillPath, 'utf8'))
  hasher.update('SKILL.md').update('\0').update(skill).update('\0')
  const hash = hasher.digest('hex').slice(0, 16)

  const lines = [
    '// GENERATED by scripts/gen-suna-context.mjs from resources/suna-context/ — DO NOT EDIT.',
    '// Drift-gated by packages/agent/src/context/context.test.ts.',
    '',
    `export const SUNA_CONTEXT_HASH: string = ${JSON.stringify(hash)}`,
    '',
    'export const SUNA_CONTEXT_FILES: Record<string, string> = {',
    ...names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(files[n])},`),
    '}',
    '',
    `export const SUNA_SKILL_FILE: string = ${JSON.stringify(skill)}`,
    '',
  ]
  return { content: lines.join('\n'), names, hash }
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const { content, names, hash } = generate()
  fs.writeFileSync(outPath, content)
  console.log(`wrote ${path.relative(repoRoot, outPath)} (${names.length} docs + skill, hash ${hash})`)
}
